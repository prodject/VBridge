                onCancel: {}
            )
        }
        .onDisappear {
            guard let draft else { return }
            let changed = originalProfile != draft
            if let idx = store.profiles.firstIndex(where: { $0.id == profileID }) {
                store.profiles[idx] = draft
                store.save()
            }
            onCommit?(draft, changed)
        }
    }

    private func applyScannedWireGuardConfig(_ raw: String) {
        let normalized = normalizeScannedText(raw)
        binding(\.wgQuickConfig).wrappedValue = normalized
    }

    private func normalizeScannedText(_ input: String) -> String {
        let trimmed = input.trimmingCharacters(in: .whitespacesAndNewlines)
        if let decoded = decodeAmneziaScannedText(trimmed) {
            return decoded
        }
        if trimmed.contains("\\n") && !trimmed.contains("\n") {
            return trimmed.replacingOccurrences(of: "\\n", with: "\n")
        }
        return trimmed
    }

    private func decodeAmneziaScannedText(_ input: String) -> String? {
        let normalized = input.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !normalized.isEmpty else { return nil }
        if normalized.contains("[Interface]") || normalized.contains("[Peer]") {
            return nil
        }

        for candidate in amneziaBase64Candidates(from: normalized) {
            guard let data = decodeBase64Payload(candidate) else { continue }
            if let config = extractWireGuardConfig(from: data) {
                return config
            }
        }
        return nil
    }

    private func amneziaBase64Candidates(from input: String) -> [String] {
        let raw = input.trimmingCharacters(in: .whitespacesAndNewlines)
        let compact = raw
            .replacingOccurrences(of: "\n", with: "")
            .replacingOccurrences(of: "\r", with: "")
            .replacingOccurrences(of: " ", with: "")

        let schemeSplitters = ["://", "wg://", "awg://", "amnezia://", "amneziawg://"]
        var candidates = [compact]

        for splitter in schemeSplitters {
            if let range = compact.range(of: splitter) {
                candidates.append(String(compact[range.upperBound...]))
            }
        }

        if let queryIndex = compact.firstIndex(of: "?") {
            candidates.append(String(compact[..<queryIndex]))
        }

        var uniqueCandidates: [String] = []
        for value in candidates {
            let trimmed = value.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty, !uniqueCandidates.contains(trimmed) else { continue }
            uniqueCandidates.append(trimmed)
        }
        return uniqueCandidates
    }

    private func decodeBase64Payload(_ input: String) -> Data? {
        let sanitized = input
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .replacingOccurrences(of: "-", with: "+")
            .replacingOccurrences(of: "_", with: "/")
        guard !sanitized.isEmpty else { return nil }

        let remainder = sanitized.count % 4
        let padded = remainder == 0 ? sanitized : sanitized + String(repeating: "=", count: 4 - remainder)
        return Data(base64Encoded: padded, options: [.ignoreUnknownCharacters])
    }

    private func extractWireGuardConfig(from data: Data) -> String? {
        let marker = Data("[Interface]".utf8)
        let peerMarker = Data("[Peer]".utf8)

        if let interfaceRange = data.range(of: marker) {
            let sliced = data[interfaceRange.lowerBound...]
            guard sliced.range(of: peerMarker) != nil,
                  let decoded = String(data: sliced, encoding: .utf8) ?? String(data: sliced, encoding: .ascii) else {
                return nil
            }
            return decoded.trimmingCharacters(in: .whitespacesAndNewlines)
        }

        if let decoded = String(data: data, encoding: .utf8) ?? String(data: data, encoding: .ascii),
           let range = decoded.range(of: "[Interface]") {
            let config = String(decoded[range.lowerBound...]).trimmingCharacters(in: .whitespacesAndNewlines)
            return config.contains("[Peer]") ? config : nil
        }

        return nil
    }

    private func generateQuickImportLink() {
        var payload: [String: Any] = [
            "name": profile.name,
            "mode": profile.transportMode.rawValue,
            "turn": profile.vkLink,
            "peer": profile.peerAddr,
            "listen": profile.listenAddr,
            "n": profile.nValue,
            "credsGroupSize": profile.credsGroupSize,
            "wg": profile.wgQuickConfig,
            "turnHost": profile.turnHost,
            "turnPort": profile.turnPort,
            "udp": profile.useUdp,
            "wrapKeyHex": profile.wrapKeyHex,
            "wdttPassword": profile.wdttPassword,
            "wdttClientKey": profile.wdttClientKey,
            "wdttServerKey": profile.wdttServerKey,
            "wdttFingerprint": profile.wdttFingerprint,
            "wdttClientIDMode": profile.wdttClientIDMode,
            "wdttUseVKCallsPreflight": profile.wdttUseVKCallsPreflight,
            "csqttPassword": profile.csqttPassword,
            "csqttClientTag": profile.csqttClientTag
        ]
        if let wdttTunnelMTU = profile.wdttTunnelMTU, wdttTunnelMTU > 0 {
            payload["wdttTunnelMTU"] = wdttTunnelMTU
        }
        if let csqttWebPort = profile.csqttWebPort, csqttWebPort > 0 {
            payload["csqttWebPort"] = csqttWebPort
        }

        guard JSONSerialization.isValidJSONObject(payload),
              let jsonData = try? JSONSerialization.data(withJSONObject: payload, options: []),
              let json = String(data: jsonData, encoding: .utf8) else {
            exportErrorMessage = "Failed to generate quick link."
            showExportError = true
            return
        }

        let base64 = Data(json.utf8).base64EncodedString()
        let link = "vbridge://\(base64)"
        UIPasteboard.general.string = link
        showLinkGeneratedAlert = true
    }

    private func applyCreatedVKCallLink(_ link: String) {
        let trimmedLink = link.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmedLink.isEmpty else {
            vkCallCreatorStatus = "VK returned an empty call link."
            return
        }

        let existingLines = profile.vkLink
            .components(separatedBy: .newlines)
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { !$0.isEmpty && $0 != trimmedLink }

        binding(\.vkLink).wrappedValue = ([trimmedLink] + existingLines).joined(separator: "\n")
        vkCallCreatorStatus = "Call created and added as the first link."
    }

    private func binding<T>(_ keyPath: WritableKeyPath<VPNProfile, T>) -> Binding<T> {
        Binding(
            get: { profile[keyPath: keyPath] },
            set: { newValue in
                if draft == nil {
                    draft = store.profiles.first(where: { $0.id == profileID })
                }
                draft?[keyPath: keyPath] = newValue
            }
        )
    }

    private func bindingToDraftProfile() -> Binding<VPNProfile> {
        Binding(
            get: { profile },
            set: { newValue in
                if draft == nil {
                    draft = store.profiles.first(where: { $0.id == profileID })
                }
                draft = newValue
            }
        )
    }

    private func mtuLabel(_ value: Int?) -> String {
        guard let value else { return "Auto (Server Suggested)" }
        return "\(value)"
    }
}

private struct WDTTAdvancedSettingsView: View {
    @Binding var profile: VPNProfile
    let presets: [Int?]
    var onAutodetectMTU: (() async throws -> Int)? = nil

    @State private var isDetectingMTU = false
    @State private var mtuStatusMessage: String?
    @State private var showMTUAlert = false
    @State private var mtuAlertTitle = ""
    @State private var mtuAlertMessage = ""

    var body: some View {
        Form {
            Section(header: Text("Runtime")) {
                Toggle(isOn: $profile.wdttUseVKCallsPreflight) {
                    VStack(alignment: .leading) {
                        Text("VK Calls Preflight")
                        Text("Disable only if you need the legacy captcha path instead of the VK Calls bootstrap path.")
                            .font(.caption)
                            .foregroundColor(.secondary)
                    }
                }

                Picker("Fingerprint", selection: $profile.wdttFingerprint) {
                    Text("Auto").tag("auto")
                    Text("Safari").tag("safari")
                    Text("Chrome").tag("chrome")
                }
                .pickerStyle(.menu)

                Picker("Client ID Filter", selection: $profile.wdttClientIDMode) {
                    Text("Default Rotation").tag("default")
                    Text("6287487").tag("6287487")
                    Text("8202606").tag("8202606")
                }
                .pickerStyle(.menu)
            }

            Section(header: Text("Tunnel MTU")) {
                Picker("Tunnel MTU", selection: $profile.wdttTunnelMTU) {
                    ForEach(presets, id: \.self) { mtu in
                        Text(mtuLabel(mtu)).tag(mtu as Int?)
                    }
                }
                .pickerStyle(.menu)

                if let mtuStatusMessage, !mtuStatusMessage.isEmpty {
                    Text(mtuStatusMessage)
                        .font(.caption)
                        .foregroundColor(.secondary)
                }

                Button {
                    guard !isDetectingMTU else { return }
                    Task {
                        await autodetectMTU()
                    }
                } label: {
                    HStack {
                        if isDetectingMTU {
                            ProgressView()
                                .progressViewStyle(.circular)
                        }
                        Text(isDetectingMTU ? "Detecting..." : "Autodetect MTU")
                    }
                }
                .disabled(isDetectingMTU || onAutodetectMTU == nil)

                VStack(alignment: .leading, spacing: 3) {
                    Text("Auto uses the MTU provisioned by the server.")
                    Text("1280: safest default for unstable mobile paths.")
                    Text("1360: balanced choice for most LTE and Wi-Fi networks.")
                    Text("1420: use on clean paths when you want lower overhead.")
                    Text("1500: only for LAN or very clean full-MTU routes.")
                }
                .font(.caption)
                .foregroundColor(.secondary)
            }
        }
        .navigationTitle("Advanced WDTT")
        .navigationBarTitleDisplayMode(.inline)
        .alert(mtuAlertTitle, isPresented: $showMTUAlert) {
            Button("OK", role: .cancel) {}
        } message: {
            Text(mtuAlertMessage)
        }
    }

    @MainActor
    private func autodetectMTU() async {
        guard let onAutodetectMTU else { return }
        isDetectingMTU = true
        mtuStatusMessage = "Testing MTU presets. The tunnel will reconnect several times."
        defer { isDetectingMTU = false }

        do {
            let detected = try await onAutodetectMTU()
            profile.wdttTunnelMTU = detected
            mtuStatusMessage = "Best MTU detected: \(detected)"
            mtuAlertTitle = "MTU Detected"
            mtuAlertMessage = "Best MTU: \(detected)"
            showMTUAlert = true
        } catch {
            mtuStatusMessage = "Autodetect failed: \(error.localizedDescription)"
            mtuAlertTitle = "Autodetect Failed"
            mtuAlertMessage = error.localizedDescription
            showMTUAlert = true
        }
    }

    private func mtuLabel(_ value: Int?) -> String {
        guard let value else { return "Auto (Server Suggested)" }
        return "\(value)"
    }
}
