                    .disableAutocorrection(true)

                Picker("Mode", selection: binding(\.transportMode)) {
                    ForEach(VPNTransportMode.allCases) { mode in
                        Text(mode.title).tag(mode)
                    }
                }
            }

            Section(header: Text("Proxy Settings")) {
                if profile.transportMode != .wdtt && profile.transportMode != .csqtt {
                    TextField("TURN Server URL", text: binding(\.vkLink))
                        .autocapitalization(.none)
                        .disableAutocorrection(true)
                }

                TextField("Peer Address (IP:Port)", text: binding(\.peerAddr))
                    .autocapitalization(.none)
                    .disableAutocorrection(true)

                if profile.transportMode != .wdtt && profile.transportMode != .csqtt {
                    TextField("Listen Address (IP:Port)", text: binding(\.listenAddr))
                        .autocapitalization(.none)
                        .disableAutocorrection(true)
                }

                Stepper("Connections (n): \(profile.nValue)", value: binding(\.nValue), in: 1...32)
                Stepper("Workers per TURN identity: \(profile.credsGroupSize)", value: binding(\.credsGroupSize), in: 1...32)
                Text("`n` controls total parallel TURN sessions. The vk-turn-proxy-ios runtime is tuned for fast 30-connection startup.")
                    .font(.caption)
                    .foregroundColor(.secondary)
            }

            if profile.transportMode != .wdtt && profile.transportMode != .csqtt {
                Section(header: Text("WireGuard Config")) {
                    TextEditor(text: binding(\.wgQuickConfig))
                        .font(.system(.footnote, design: .monospaced))
                        .frame(minHeight: 150)
                        .autocapitalization(.none)
                        .disableAutocorrection(true)
                }
            }

            if profile.transportMode == .srtpCommunity {
                Section(header: Text("SRTP-Community")) {
                    TextField("WRAP Key Hex", text: binding(\.wrapKeyHex))
                        .font(.system(.footnote, design: .monospaced))
                        .autocapitalization(.none)
                        .disableAutocorrection(true)

                    Text("64 hex characters generated by the SRTP-WRAP server.")
                        .font(.caption)
                        .foregroundColor(.secondary)
                }
            }

            if profile.transportMode == .wdtt {
                Section(header: Text("WDTT")) {
                    TextField("VK Call URL or Hash", text: binding(\.vkLink))
                        .autocapitalization(.none)
                        .disableAutocorrection(true)

